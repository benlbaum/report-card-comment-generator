const tick = () => new Promise(resolve => setImmediate(resolve));

function setup(t, stored) {
  const errors = [];
  const console = new VirtualConsole();
  console.on('jsdomError', error => errors.push(error));
  const dom = new JSDOM(html, {
    url: 'https://report-card.test/', runScripts: 'dangerously', virtualConsole: console,
    beforeParse(window) {
      window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
      window.HTMLDialogElement.prototype.close = function (value = '') { this.returnValue = value; this.open = false; this.dispatchEvent(new window.Event('close')); };
      window.HTMLElement.prototype.scrollIntoView = function () {};
      Object.defineProperty(window.crypto, 'randomUUID', { value: () => webcrypto.randomUUID() });
      if (stored) window.localStorage.setItem('report-card-comment-builder-v2', JSON.stringify(stored));
    }
  });
  t.after(() => { dom.window.close(); assert.deepEqual(errors.map(e => e.message), []); });
  const $ = id => dom.window.document.getElementById(id);
  const change = (id, value, type = 'change') => { $(id).value = value; $(id).dispatchEvent(new dom.window.Event(type, { bubbles: true })); };
  const saved = () => JSON.parse(dom.window.localStorage.getItem('report-card-comment-builder-v2'));
  const tab = (container, name) => [...$(container).children].find(button => button.textContent === name);
  const choose = value => { const radio = [...dom.window.document.querySelectorAll('[name="phraseChoice"]')].find(el => el.value === value); radio.checked = true; radio.dispatchEvent(new dom.window.Event('change', { bubbles: true })); };
  const choice = () => dom.window.document.querySelector('[name="phraseChoice"]:checked')?.value;
  return { window: dom.window, document: dom.window.document, $, change, saved, tab, choose, choice };
}

